        public static function init() {
            add_action('init', array(__CLASS__, 'load_textdomain'), 1);
            add_filter('gettext', array(__CLASS__, 'translate'), 20, 3);
            add_filter('gettext_with_context', array(__CLASS__, 'translate_context'), 20, 4);
            add_filter('plugin_locale', array(__CLASS__, 'plugin_locale'), 10, 2);

            if (is_admin()) {
                add_action('admin_bar_menu', array(__CLASS__, 'language_switcher'), 100);
                add_action('admin_init', array(__CLASS__, 'handle_language_switch'));
            }

            self::load_translations();

            if (file_exists(__DIR__ . '/class-uapm-admin-assets.php')) {
                require_once __DIR__ . '/class-uapm-admin-assets.php';
            }
        }

        public static function load_textdomain() {
            load_plugin_textdomain(
                'ua-project-manager',
                false,
                dirname(plugin_basename(UAPM_FILE)) . '/languages'
            );
        }

        public static function plugin_locale($locale, $domain) {
            if ($domain !== 'ua-project-manager') {
                return $locale;
            }

            $language = self::get_language();

            if ($language === 'uk') {
                return 'uk';
            }

            return 'en_US';
        }

        public static function get_language() {
            if (isset($_GET['uapm_language'])) {
                $language = sanitize_key(wp_unslash($_GET['uapm_language']));

                if (in_array($language, array('uk', 'en'), true)) {
                    return $language;
                }
            }

            if (is_user_logged_in()) {
                $user_language = get_user_meta(
                    get_current_user_id(),
                    'uapm_language',
                    true
                );

                if (in_array($user_language, array('uk', 'en'), true)) {
                    return $user_language;
                }
            }

            $locale = determine_locale();

            if (strpos($locale, 'uk') === 0) {
                return 'uk';
            }

            return 'en';
        }

