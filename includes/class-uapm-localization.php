        public static function init() {
            add_action('init', array(__CLASS__, 'load_textdomain'), 1);
            add_filter('gettext', array(__CLASS__, 'translate'), 20, 3);
            add_filter('gettext_with_context', array(__CLASS__, 'translate_context'), 20, 4);

            if (is_admin()) {
                add_action('admin_bar_menu', array(__CLASS__, 'language_switcher'), 100);
                add_action('admin_init', array(__CLASS__, 'handle_language_switch'));
            }

            if (file_exists(__DIR__ . '/class-uapm-admin-assets.php')) {
                require_once __DIR__ . '/class-uapm-admin-assets.php';
            }
        }

        public static function load_textdomain() {
            load_plugin_textdomain(
                'ua-project-manager',
                false,
                dirname(plugin_basename(UAPM_FILE)) . '/languages'
            );
        }

        public static function get_language() {
            if (isset($_GET['uapm_language'])) {
                $language = sanitize_key(wp_unslash($_GET['uapm_language']));

                if (in_array($language, array('uk', 'en'), true)) {
                    return $language;
                }
            }

            if (is_user_logged_in()) {
                $user_language = get_user_meta(
                    get_current_user_id(),
                    'uapm_language',
                    true
                );

                if (in_array($user_language, array('uk', 'en'), true)) {
                    return $user_language;
                }
            }

            return strpos(determine_locale(), 'uk') === 0 ? 'uk' : 'en';
        }

        public static function translate($translated, $text, $domain) {
            if ($domain !== 'ua-project-manager' || self::get_language() !== 'uk') {
                return $translated;
            }

            return isset(self::$translations[$text])
                ? self::$translations[$text]
                : $translated;
        }

        public static function translate_context($translated, $text, $context, $domain) {
            return self::translate($translated, $text, $domain);
        }

        public static function language_switcher($admin_bar) {
            if (!is_object($admin_bar)) {
                return;
            }

            $current = self::get_language();
            $target = $current === 'uk' ? 'en' : 'uk';
            $label = $current === 'uk' ? 'English' : 'Українська';

            $url = add_query_arg(
                array(
                    'uapm_language' => $target,
                    '_wpnonce' => wp_create_nonce('uapm_language_switch'),
                ),
                remove_query_arg(array('uapm_language', '_wpnonce'))
            );

            $admin_bar->add_node(array(
                'id' => 'uapm-language',
                'title' => esc_html($label),
                'href' => esc_url($url),
            ));
        }

        public static function handle_language_switch() {
            if (!isset($_GET['uapm_language'], $_GET['_wpnonce'])) {
                return;
            }

            $language = sanitize_key(wp_unslash($_GET['uapm_language']));

            if (!in_array($language, array('uk', 'en'), true)) {
                return;
            }

            if (!wp_verify_nonce(
                sanitize_text_field(wp_unslash($_GET['_wpnonce'])),
                'uapm_language_switch'
            )) {
                return;
            }

            if (is_user_logged_in()) {
                update_user_meta(
                    get_current_user_id(),
                    'uapm_language',
                    $language
                );
            }

            wp_safe_redirect(remove_query_arg(array('uapm_language', '_wpnonce')));
            exit;
        }
    }

